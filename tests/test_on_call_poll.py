import importlib.util
import json
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path

spec = importlib.util.spec_from_file_location("poll_alerts", Path(__file__).parents[1] / "on-call-engineer" / "poll_alerts.py")
poll_alerts = importlib.util.module_from_spec(spec)
spec.loader.exec_module(poll_alerts)

ALERT = {"fingerprint": "f1", "startsAt": "t1", "labels": {"alertname": "PersonalEvents5xx"}}


def test_new_alerts_dedups_until_refire():
    seen = set()
    assert poll_alerts.new_alerts([ALERT], seen) == [ALERT]
    assert poll_alerts.new_alerts([ALERT], seen) == []
    assert poll_alerts.new_alerts([{**ALERT, "startsAt": "t2"}], seen) == [{**ALERT, "startsAt": "t2"}]


def test_new_alerts_skips_grafana_plugin_rules_only():
    heartbeat = {"fingerprint": "f2", "startsAt": "t1", "labels": {
        "alertname": "asserts_up", "__grafana_autogenerated__": "true", "__grafana_origin": "plugin/grafana-asserts-app"}}
    # simplified routing (rule sends straight to a contact point) also sets __grafana_autogenerated__
    routed = {"fingerprint": "f3", "startsAt": "t1", "labels": {
        "alertname": "Personal event creation failing", "__grafana_autogenerated__": "true",
        "__grafana_receiver__": "MoodleHelper owner email"}}
    assert poll_alerts.new_alerts([heartbeat, routed, ALERT], set()) == [routed, ALERT]


def test_firing_alerts_calls_alertmanager_with_token(monkeypatch):
    requests = []

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            requests.append((self.path, self.headers["Authorization"]))
            body = json.dumps([ALERT]).encode()
            self.send_response(200)
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    server = HTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=server.handle_request, daemon=True).start()
    monkeypatch.setenv("GRAFANA_URL", f"http://127.0.0.1:{server.server_port}/")
    monkeypatch.setenv("GRAFANA_TOKEN", "test-token")

    assert poll_alerts.firing_alerts() == [ALERT]
    assert requests == [("/api/alertmanager/grafana/api/v2/alerts?active=true&silenced=false&inhibited=false", "Bearer test-token")]
    server.server_close()


def test_dispatch_runs_read_only_agent(monkeypatch, tmp_path):
    calls = []
    monkeypatch.setattr(poll_alerts, "LOG_DIR", tmp_path)
    monkeypatch.setattr(poll_alerts.subprocess, "Popen", lambda args, **kw: calls.append(args))

    poll_alerts.dispatch(ALERT)

    [args] = calls
    assert args[:2] == ["claude", "-p"] and '"PersonalEvents5xx"' in args[2]
    assert args[3:] == ["--allowedTools", "Read,Grep,Glob"]
    assert len(list(tmp_path.glob("*-f1.md"))) == 1
